#!/usr/bin/env node
// Writes GridFormatter/engine/fluentTokens.ts: the colour token allow-list
// (the schema's $defs.fluentColorToken.enum) with each token's Fluent 9
// webLightTheme value, packed into one short string so the control bundle
// stays small. The runtime emits `var(--<token>, <light value>)`, so the light
// value is only a fallback for places where the theme's CSS variables aren't
// defined; contrast checks and pill text use it too.
//
// Run it after scripts/generate-token-list.mjs changes the schema's token list,
// or after the declared Fluent version changes, and commit the result.
// tests/fluentTokens.test.ts fails when the committed file is out of date.
//
// Usage: node scripts/generate-token-fallbacks.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

/** Used if webLightTheme has no value for a token: mid grey reads on light and dark backgrounds. */
const NEUTRAL_FALLBACK = "#808080";
const PREFIX = "color";
const MAX_SHARED = 35; // one base-36 digit

const controlDir = fileURLToPath(new URL("..", import.meta.url));
const schemaPath = join(controlDir, "config", "grid-format.schema.json");
const outputPath = join(controlDir, "GridFormatter", "engine", "fluentTokens.ts");

const require = createRequire(join(controlDir, "package.json"));
const { webLightTheme } = require("@fluentui/react-components");
const { version } = require("@fluentui/react-components/package.json");

const names = [...JSON.parse(readFileSync(schemaPath, "utf8")).$defs.fluentColorToken.enum].sort();
const missing = names.filter((name) => typeof webLightTheme[name] !== "string");
if (missing.length > 0) console.warn(`No webLightTheme value for ${missing.join(", ")}; using ${NEUTRAL_FALLBACK}.`);

let previous = "";
const packed = names
  .map((name) => {
    const short = name.slice(PREFIX.length);
    let shared = 0;
    while (shared < MAX_SHARED && shared < previous.length && short[shared] === previous[shared]) shared++;
    previous = short;
    const raw = typeof webLightTheme[name] === "string" ? webLightTheme[name] : NEUTRAL_FALLBACK;
    const hex = /^#([0-9a-f]{6})$/i.exec(raw);
    const value = hex ? hex[1].toLowerCase() : raw.replace(/\s+/g, "");
    return `${shared.toString(36)}${short.slice(shared)}=${value}`;
  })
  .join("|");

writeFileSync(
  outputPath,
  `// Generated by scripts/generate-token-fallbacks.mjs from config/grid-format.schema.json
// and @fluentui/react-components@${version} webLightTheme. Don't edit by hand.
//
// Format: "|"-separated entries "<p><rest>=<value>", sorted by name. A name
// drops its "color" prefix; <p> is one base-36 digit: how many leading
// characters it shares with the previous name. <value> is six hex digits
// (without "#") or a literal CSS colour. Unpacked by colours.ts.
export const PACKED_FLUENT_COLOR_TOKENS =
\t"${packed}";
`,
);
console.log(`Wrote ${names.length} tokens (${packed.length} characters) to ${outputPath}`);
