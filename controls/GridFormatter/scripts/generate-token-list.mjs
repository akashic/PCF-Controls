#!/usr/bin/env node
// Writes the Fluent 9 colour token allow-list into config/grid-format.schema.json
// ($defs.fluentColorToken.enum). Run it after the declared Fluent version changes,
// and commit the result. Then run generate-token-fallbacks.mjs, which copies the
// list (with light-theme fallbacks) into the control's runtime validator.
//
// Usage:
//   node scripts/generate-token-list.mjs
//       Reads the `tokens` export of @fluentui/react-components, if it is installed.
//   node scripts/generate-token-list.mjs --from <dir> [--from <dir> ...]
//       Reads lib/tokens.js of one or more unpacked @fluentui/tokens packages
//       (`npm pack @fluentui/tokens@<version>`) as text, without running it.
//       With several, keeps only the tokens present in all of them, so the list
//       is safe for every Fluent version the control may run against.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const controlDir = fileURLToPath(new URL("..", import.meta.url));
const schemaPath = join(controlDir, "config", "grid-format.schema.json");

const fromDirs = process.argv.flatMap((arg, i, all) => (arg === "--from" ? [all[i + 1]] : []));

/** Colour token names declared in an unpacked @fluentui/tokens package. */
function tokensFromPackage(dir) {
  const source = readFileSync(join(dir, "lib", "tokens.js"), "utf8");
  const names = [...source.matchAll(/\b(color[A-Za-z0-9]+): 'var\(--\1\)'/g)].map((m) => m[1]);
  const { version } = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  if (names.length === 0) throw new Error(`No colour tokens found in ${dir}/lib/tokens.js`);
  return { source: `@fluentui/tokens@${version}`, names: new Set(names) };
}

async function tokensFromInstalledPackage() {
  const require = createRequire(join(controlDir, "package.json"));
  let entry;
  try {
    entry = require.resolve("@fluentui/react-components");
  } catch {
    console.error(
      "@fluentui/react-components isn't installed. Either install it, or pass --from <dir> with unpacked @fluentui/tokens packages.",
    );
    process.exit(1);
  }
  const { tokens } = await import(entry);
  const { version } = require("@fluentui/react-components/package.json");
  return {
    source: `@fluentui/react-components@${version}`,
    names: new Set(Object.keys(tokens).filter((name) => name.startsWith("color"))),
  };
}

const sets = fromDirs.length > 0 ? fromDirs.map(tokensFromPackage) : [await tokensFromInstalledPackage()];
const [first, ...rest] = sets;
const names = [...first.names].filter((name) => rest.every((set) => set.names.has(name))).sort();

const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
schema.$defs.fluentColorToken = {
  description:
    "Fluent 9 colour token name. Generated by scripts/generate-token-list.mjs; don't edit by hand.",
  $comment: `Colour tokens present in ${sets.map((s) => s.source).join(" and ")}.`,
  enum: names,
};
writeFileSync(schemaPath, `${JSON.stringify(schema, null, 2)}\n`);
console.log(`Wrote ${names.length} colour tokens to ${schemaPath}`);
